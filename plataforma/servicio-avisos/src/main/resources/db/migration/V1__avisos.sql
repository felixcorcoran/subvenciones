-- Quien se apunta: su email, el perfil de su negocio (lo mismo que pregunta el radar) y un token
-- secreto para confirmar, cambiar el perfil o darse de baja desde los enlaces de los correos.
CREATE TABLE suscriptores (
    id             UUID PRIMARY KEY,
    email          VARCHAR(254) NOT NULL UNIQUE,
    provincia      VARCHAR(6)   NOT NULL,
    municipio      VARCHAR(80)  NOT NULL,
    forma          VARCHAR(10)  NOT NULL,
    empleados      INTEGER      NOT NULL,
    antiguedad     VARCHAR(6)   NOT NULL,
    sector         VARCHAR(1)   NOT NULL,
    token          VARCHAR(64)  NOT NULL UNIQUE,
    estado         VARCHAR(10)  NOT NULL,
    consentimiento VARCHAR(20)  NOT NULL,
    creado         TIMESTAMPTZ  NOT NULL,
    confirmado     TIMESTAMPTZ,
    ultimo_alta    TIMESTAMPTZ,
    ultimo_aviso   TIMESTAMPTZ
);

-- Las convocatorias leídas que han llegado por Kafka: se reparten una sola vez
CREATE TABLE novedades (
    codigo    VARCHAR(20) PRIMARY KEY,
    titulo    TEXT        NOT NULL,
    categoria VARCHAR(10),
    cierre    DATE,
    llegada   TIMESTAMPTZ NOT NULL,
    repartida BOOLEAN     NOT NULL DEFAULT false
);

CREATE INDEX novedades_sin_repartir ON novedades (codigo) WHERE NOT repartida;

-- Cada ayuda que encaja con alguien, hasta que sale en su correo
CREATE TABLE avisos (
    id            BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    suscriptor_id UUID        NOT NULL REFERENCES suscriptores (id) ON DELETE CASCADE,
    codigo        VARCHAR(20) NOT NULL,
    estado        VARCHAR(6)  NOT NULL,
    creado        TIMESTAMPTZ NOT NULL,
    enviado       TIMESTAMPTZ,
    UNIQUE (suscriptor_id, codigo)
);

CREATE INDEX avisos_pendientes ON avisos (suscriptor_id) WHERE enviado IS NULL;

CREATE TABLE pasadas (
    id      BIGSERIAL PRIMARY KEY,
    fecha   TIMESTAMPTZ NOT NULL,
    resumen JSONB       NOT NULL
);

CREATE TABLE eventos_procesados (
    id        UUID PRIMARY KEY,
    procesado TIMESTAMPTZ NOT NULL
);
